"""Run before publishing: python tools/check-content.py [--strict]."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import unquote, urlsplit
from collections import Counter
import json
import sys

ROOT = Path(__file__).resolve().parent.parent

class Content(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids, self.references, self.anchors = [], set(), set()

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        if attrs.get('id'):
            self.ids.append(attrs['id'])
        for key in ('src', 'href', 'data-pdf', 'data-now-src', 'data-unavailable-href'):
            value = attrs.get(key, '')
            if value.startswith('#'):
                if len(value) > 1:
                    self.anchors.add(unquote(value[1:]))
            elif value and not urlsplit(value).scheme and not value.startswith('//'):
                self.references.add(unquote(urlsplit(value).path))
        for candidate in attrs.get('srcset', '').split(','):
            parts = candidate.strip().split()
            if parts:
                self.references.add(unquote(parts[0]))

content = Content()
content.feed((ROOT / 'index.html').read_text(encoding='utf-8'))
missing = sorted(ref for ref in content.references if ref != 'js/content-status.js' and not (ROOT / ref).is_file())
report = {
    'missing': missing,
    'duplicateIds': [key for key, count in Counter(content.ids).items() if count > 1],
    'brokenAnchors': sorted(content.anchors - set(content.ids)),
    'checked': len(content.references),
}
(ROOT / 'data/content-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
# Local manifest also works offline; regenerate when adding the real materials.
(ROOT / 'js/content-status.js').write_text(
    '// Generated by tools/check-content.py; do not edit manually.\n'
    + 'window.bustuchinMissingAssets = new Set(' + json.dumps(missing, ensure_ascii=False) + ');\n', encoding='utf-8')
print(json.dumps(report, ensure_ascii=True, indent=2))
if report['duplicateIds'] or report['brokenAnchors'] or ('--strict' in sys.argv and missing):
    sys.exit(1)
